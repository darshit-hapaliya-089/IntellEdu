/** All quizzes belonging to one subject, in bank order. */
export function getQuizzesBySubject(subjectId: SubjectId): Quiz[] {
  return QUIZ_BANK.filter((quiz) => quiz.subjectId === subjectId);
}

/** Look up a single quiz by id. */
export function getQuizById(quizId: string): Quiz | undefined {
  return QUIZ_BANK.find((quiz) => quiz.id === quizId);
}

/** Total number of questions in the bank — used on the hub header. */
export const TOTAL_QUESTION_COUNT = QUIZ_BANK.reduce(
  (sum, quiz) => sum + quiz.questions.length,
  0
);
